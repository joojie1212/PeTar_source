inline double eccentricityFactor(const double eccentricity) {
    if (!(eccentricity >= 0.0 && eccentricity < 1.0))
        return std::numeric_limits<double>::quiet_NaN();
    if (eccentricity == 0.0) return 1.0;

    const double one_minus_e2 = (1.0-eccentricity)*(1.0+eccentricity);
    if (eccentricity > eccentricity_switch)
        return (768.0/425.0)*std::pow(one_minus_e2, 3.5);

    const double u = -std::log1p(-eccentricity);
    const double position = u*(table_size-1)/u_max;
    std::size_t lower = static_cast<std::size_t>(position);
    if (lower >= table_size-1) lower = table_size-2;
    const double fraction = position-lower;
    const double log_factor = log_factor_table[lower]
        + fraction*(log_factor_table[lower+1]-log_factor_table[lower]);
    return std::exp(log_factor);
}

